SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME,
    COUNT(A.APPOINTMENT_ID) AS APPOINTMENT_COUNT
FROM EMPLOYEES E
LEFT JOIN APPOINTMENTS A
    ON E.EMPLOYEE_ID = A.EMPLOYEE_ID
GROUP BY
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME
ORDER BY E.EMPLOYEE_ID; 

FROM SERVICES;
SELECT 
    A.APPOINTMENT_ID,
    C.FIRST_NAME || ' ' || C.LAST_NAME AS CLIENT_NAME,
    E.FIRST_NAME || ' ' || E.LAST_NAME AS EMPLOYEE_NAME,
    S.SERVICE_NAME
FROM APPOINTMENTS A
JOIN CLIENTS C
    ON A.CLIENT_ID = C.CLIENT_ID
JOIN EMPLOYEES E
    ON A.EMPLOYEE_ID = E.EMPLOYEE_ID
JOIN SERVICES S
    ON A.SERVICE_ID = S.SERVICE_ID
ORDER BY A.APPOINTMENT_ID;

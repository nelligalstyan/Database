    P.PAYMENT_ID,
    P.APPOINTMENT_ID,
    A.CLIENT_ID,
    A.EMPLOYEE_ID,
    A.SERVICE_ID,
    A.APPOINTMENT_DATE,
    A.APPOINTMENT_TIME,
    A.STATUS,
    P.AMOUNT,
    P.PAYMENT_METHOD,
    P.PAYMENT_DATE,
    P.PAYMENT_STATUS

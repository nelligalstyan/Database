CREATE TABLE Office (
    Office_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Address VARCHAR2(200),
    Phone_number VARCHAR2(30),
    State VARCHAR2(100),
    CONSTRAINT pk_office PRIMARY KEY (Office_id)
);

CREATE TABLE Doctor (
    Doctor_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR2(100) NOT NULL,
    Address VARCHAR2(200),
    Contact_phone VARCHAR2(30),
    Area_of_specialization VARCHAR2(100),
    Office_id NUMBER,
    CONSTRAINT pk_doctor PRIMARY KEY (Doctor_id),
    CONSTRAINT fk_doctor_office
        FOREIGN KEY (Office_id)
        REFERENCES Office(Office_id)
);

CREATE TABLE Patient (
    Patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR2(100) NOT NULL,
    Address VARCHAR2(200),
    Phone_number VARCHAR2(30),
    Health_record_number VARCHAR2(50) UNIQUE,
    Date_of_birth DATE,
    CONSTRAINT pk_patient PRIMARY KEY (Patient_id)
);

CREATE TABLE Doctor_Patient (
    Doctor_id NUMBER,
    Patient_id NUMBER,
    CONSTRAINT pk_doctor_patient
        PRIMARY KEY (Doctor_id, Patient_id),
    CONSTRAINT fk_dp_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_dp_patient
        FOREIGN KEY (Patient_id)
        REFERENCES Patient(Patient_id)
);

CREATE TABLE Appointment (
    Appointment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Appointment_date DATE NOT NULL,
    Appointment_time VARCHAR2(10),
    Status VARCHAR2(30),
    Doctor_id NUMBER NOT NULL,
    Patient_id NUMBER NOT NULL,
    Office_id NUMBER NOT NULL,
    CONSTRAINT pk_appointment
        PRIMARY KEY (Appointment_id),
    CONSTRAINT fk_appointment_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_appointment_patient
        FOREIGN KEY (Patient_id)
        REFERENCES Patient(Patient_id),
    CONSTRAINT fk_appointment_office
        FOREIGN KEY (Office_id)
        REFERENCES Office(Office_id)
);

CREATE TABLE Diagnosis (
    Diagnosis_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Diagnosis_date DATE,
    Description VARCHAR2(500),
    Doctor_id NUMBER NOT NULL,
    Patient_id NUMBER NOT NULL,
    CONSTRAINT pk_diagnosis
        PRIMARY KEY (Diagnosis_id),
    CONSTRAINT fk_diagnosis_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_diagnosis_patient
        FOREIGN KEY (Patient_id)
        REFERENCES Patient(Patient_id)
);

CREATE TABLE Blood_test (
    BloodTest_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Test_date DATE,
    Test_type VARCHAR2(100),
    Result VARCHAR2(500),
    Doctor_id NUMBER NOT NULL,
    Patient_id NUMBER NOT NULL,
    CONSTRAINT pk_blood_test
        PRIMARY KEY (BloodTest_id),
    CONSTRAINT fk_blood_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_blood_patient
        FOREIGN KEY (Patient_id)
        REFERENCES Patient(Patient_id)
);

CREATE TABLE X_RAY (
    X_RAY_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    X_RAY_date DATE,
    Type VARCHAR2(100),
    Result VARCHAR2(500),
    Doctor_id NUMBER NOT NULL,
    Patient_id NUMBER NOT NULL,
    CONSTRAINT pk_xray
        PRIMARY KEY (X_RAY_id),
    CONSTRAINT fk_xray_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_xray_patient

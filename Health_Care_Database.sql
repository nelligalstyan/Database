    CONSTRAINT fk_prescription_doctor
        FOREIGN KEY (Doctor_id)
        REFERENCES Doctor(Doctor_id),
    CONSTRAINT fk_prescription_patient
        FOREIGN KEY (Patient_id)
        REFERENCES Patient(Patient_id)
